const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{const browser=await chromium.launch({channel:'chrome',headless:true});try{
 const page=await browser.newPage();
 const base=process.env.CATALOGUE_TEST_URL||'http://localhost:8080';
 let release;const gate=new Promise(resolve=>release=resolve);
 await page.route('**/catalogue.js?*',async route=>{await gate;await route.continue();});
 await page.goto(base+'/catalogue.html?category=CCTV%20Systems',{waitUntil:'commit'});
 await page.locator('#product-browser').waitFor({state:'visible'});
 assert.equal(await page.locator('#category-landing').isVisible(),false);
 assert.equal(await page.locator('#catalogue-page-title').textContent(),'CCTV Systems');
 assert.equal(await page.locator('#result-count').textContent(),'Loading products…');
 release();
 await page.waitForFunction(()=>document.querySelector('#products').getAttribute('aria-busy')==='false');
 assert.equal(await page.locator('#category-landing').isVisible(),false);
 assert.ok(await page.locator('.product-card').count()>0);
 await page.goto(base+'/catalogue.html');
 await page.locator('#category-landing').waitFor({state:'visible'});
 assert.equal(await page.locator('#product-browser').isVisible(),false);
 await page.goto(base+'/catalogue.html?category=DoesNotExist');
 await page.locator('#category-landing').waitFor({state:'visible'});
 assert.equal(await page.locator('#catalogue-page-title').textContent(),'OUR PRODUCTS & SERVICES');
 assert.equal(await page.locator('#product-browser').isVisible(),false);
 await page.setViewportSize({width:390,height:844});
 await page.goto(base+'/catalogue.html?view=all');
 await page.waitForFunction(()=>document.querySelector('#products').getAttribute('aria-busy')==='false');
 assert.equal(await page.locator('#catalogue-page-title').textContent(),'All products');
 assert.equal(await page.locator('#category-landing').isVisible(),false);
 console.log('Passed: delayed module shows category loading view without landing flash; products load; category landing, invalid category and mobile all-products work.');
}finally{await browser.close();}})().catch(error=>{console.error(error);process.exitCode=1;});
